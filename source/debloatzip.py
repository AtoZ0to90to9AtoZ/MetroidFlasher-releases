#!/usr/bin/env python3
"""debloatzip - turn an appscan report into a recovery-flashable zip that removes the chosen ROM apps.

  python debloatzip.py <appscan.json> [--out MetroidDebloat.zip] [--pick] [--yes]

--pick opens a window with every conflict: "remove" ones start ticked, "ask first" ones start unticked.
Without --pick, the "remove" list is used as is. Flash the zip in recovery right AFTER the GApps zip
(adb sideload), before the first boot.

The zip is a plain shell update-binary: it maps the slot's system/system_ext/product from the
super partition read-write, deletes only exact app folders under app/ or priv-app/, and never touches
anything on the protected list. It removes nothing it cannot find; it prints what it did.
"""
import io
import json
import os
import sys
import time
import zipfile

ALLOWED_ROOTS = ("/system/app/", "/system/priv-app/", "/system_ext/app/", "/system_ext/priv-app/",
                 "/product/app/", "/product/priv-app/")

UPDATE_BINARY = r'''#!/sbin/sh
# MetroidDebloat - generated by MetroidFlasher debloatzip.py on @DATE@
OUTFD="/proc/self/fd/$2"
ZIP="$3"
ui_print() { echo "ui_print $1" > "$OUTFD"; echo "ui_print" > "$OUTFD"; }
abort() { ui_print "ERROR: $1"; cleanup; exit 1; }
MNT=/tmp/mdebloat
cleanup() { for p in system system_ext product; do umount "$MNT/$p" 2>/dev/null; done; }

ui_print "MetroidDebloat: removing ROM apps that duplicate your GApps"
SLOT=$(getprop ro.boot.slot_suffix)
[ -z "$SLOT" ] && SLOT=$(grep -o 'androidboot.slot_suffix=_[ab]' /proc/cmdline | cut -d= -f2)
ui_print "- slot: ${SLOT:-unknown}"

mount_rw() {
  p="$1"
  mkdir -p "$MNT/$p"
  for dev in "/dev/block/mapper/$p$SLOT" "/dev/block/mapper/$p"; do
    [ -e "$dev" ] || continue
    real=$(readlink -f "$dev")
    # Other installers (NikGapps...) often leave the partition mounted read-only somewhere; a second rw mount of
    # the same device then fails. Unmount every existing mount of it first (deepest first).
    for mp in $(grep -E "^($dev|$real) " /proc/mounts | cut -d' ' -f2 | sort -r); do
      umount "$mp" 2>/dev/null || umount -l "$mp" 2>/dev/null
    done
    blockdev --setrw "$dev" 2>/dev/null; blockdev --setrw "$real" 2>/dev/null
    if mount -t ext4 -o rw "$dev" "$MNT/$p" 2>/tmp/mdebloat.err || mount -t ext4 -o rw "$real" "$MNT/$p" 2>>/tmp/mdebloat.err; then
      ui_print "- $p: mounted read-write"
      return 0
    fi
    # last resort: it is still mounted somewhere -> remount that read-write
    mp=$(grep -E "^($dev|$real) " /proc/mounts | head -1 | cut -d' ' -f2)
    if [ -n "$mp" ] && mount -o remount,rw "$mp" 2>>/tmp/mdebloat.err; then
      ui_print "- $p: remounted read-write at $mp"
      MP_OVERRIDE="$mp"
      return 0
    fi
  done
  ui_print "- $p: COULD NOT MOUNT READ-WRITE: $(head -c 200 /tmp/mdebloat.err)"
  return 1
}

# where /system/... lives inside the mounted partition
root_of() {
  b="$MNT/$1"; [ -n "$MP_OVERRIDE" ] && b="$MP_OVERRIDE"
  case "$1" in
    system) [ -d "$b/system/app" ] && echo "$b/system" || echo "$b" ;;
    *) echo "$b" ;;
  esac
}

unzip -o -p "$ZIP" debloat.list > /tmp/mdebloat.list || abort "no debloat.list in zip"
for p in system system_ext product; do
  grep -q "^/$p/" /tmp/mdebloat.list || continue
  MP_OVERRIDE=""
  mount_rw "$p" || continue
  base=$(root_of "$p")
  grep "^/$p/" /tmp/mdebloat.list | while IFS= read -r path; do
    rel="${path#/$p/}"
    case "$rel" in app/*|priv-app/*) ;; *) ui_print "  refused (not an app folder): $path"; continue ;; esac
    case "$rel" in *..*|*/*/*) ui_print "  refused (bad path): $path"; continue ;; esac
    target="$base/$rel"
    if [ -d "$target" ] && [ ! -L "$target" ]; then
      rm -rf "$target" && ui_print "  removed $path"
    else
      ui_print "  not found (ok): $path"
    fi
  done
  sync
  [ -z "$MP_OVERRIDE" ] && umount "$MNT/$p"
done
ui_print "MetroidDebloat done. Rebooting to the bootloader in 3 seconds..."
# Recovery must see a clean exit first, then the phone drops to fastboot by itself so the
# tool's final `fastboot -w` can run (crDroid recovery refuses `adb reboot bootloader` after a sideload).
(sleep 3; reboot bootloader) &
exit 0
'''


def selection_from_report(report, pick=False):
    conflicts = [c for c in report["conflicts"] if c["action"] in ("remove", "ask")]
    chosen = {c["path"]: c["action"] == "remove" for c in conflicts}
    if pick:
        chosen = run_picker(conflicts, chosen)
        if chosen is None:
            print("Cancelled, no zip made.")
            sys.exit(1)
    return [c for c in conflicts if chosen.get(c["path"])]


def run_picker(conflicts, chosen):
    import tkinter as tk
    from tkinter import ttk
    result = {"ok": False}
    win = tk.Tk()
    win.title("MetroidDebloat - pick ROM apps to remove")
    ttk.Label(win, text="Ticked apps are removed before first boot. Recommended ones are pre-ticked;\n"
                        "\"ask\" ones are unticked - read why before ticking them.", padding=8).pack(anchor="w")
    frame = ttk.Frame(win, padding=8)
    frame.pack(fill="both", expand=True)
    canvas = tk.Canvas(frame, width=900, height=480)
    sb = ttk.Scrollbar(frame, orient="vertical", command=canvas.yview)
    inner = ttk.Frame(canvas)
    inner.bind("<Configure>", lambda e: canvas.configure(scrollregion=canvas.bbox("all")))
    canvas.create_window((0, 0), window=inner, anchor="nw")
    canvas.configure(yscrollcommand=sb.set)
    canvas.pack(side="left", fill="both", expand=True)
    sb.pack(side="right", fill="y")
    vars_ = {}
    for c in conflicts:
        v = tk.BooleanVar(value=chosen[c["path"]])
        vars_[c["path"]] = v
        tag = "RECOMMENDED" if c["action"] == "remove" else "ASK FIRST"
        ttk.Checkbutton(inner, variable=v, text=f"[{tag}] {c['path']}   ({c['package']})").pack(anchor="w")
        ttk.Label(inner, text="      " + c["reason"], wraplength=860, foreground="#555").pack(anchor="w")
    bar = ttk.Frame(win, padding=8)
    bar.pack(fill="x")

    def ok():
        result["ok"] = True
        win.destroy()
    ttk.Button(bar, text="Make zip", command=ok).pack(side="right")
    ttk.Button(bar, text="Cancel", command=win.destroy).pack(side="right", padx=8)
    win.mainloop()
    if not result["ok"]:
        return None
    return {p: v.get() for p, v in vars_.items()}


def build_zip(paths, out):
    for p in paths:
        if not p.startswith(ALLOWED_ROOTS) or ".." in p:
            raise SystemExit(f"refusing path {p}")
    body = UPDATE_BINARY.replace("@DATE@", time.strftime("%Y-%m-%d %H:%M"))
    with zipfile.ZipFile(out, "w", zipfile.ZIP_DEFLATED) as z:
        z.writestr("META-INF/com/google/android/update-binary", body.replace("\r\n", "\n"))
        z.writestr("META-INF/com/google/android/updater-script", "# dummy - update-binary does the work\n")
        z.writestr("debloat.list", "".join(p + "\n" for p in paths))


def main():
    argv = sys.argv[1:]
    out = "MetroidDebloat.zip"
    if "--out" in argv:
        i = argv.index("--out")
        out = argv[i + 1]
        del argv[i:i + 2]
    pick = "--pick" in argv
    argv = [a for a in argv if not a.startswith("--")]
    with open(argv[0], encoding="utf-8") as f:
        report = json.load(f)
    sel = selection_from_report(report, pick)
    paths = sorted({os.path.dirname(c["path"]) for c in sel})
    print(f"{len(paths)} app folders will be removed:")
    for c in sel:
        print(f"  {os.path.dirname(c['path'])}  ({c['package']})")
    build_zip(paths, out)
    print(f"\nZip: {os.path.abspath(out)}")


if __name__ == "__main__":
    main()
